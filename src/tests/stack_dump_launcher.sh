#!/bin/bash
# ctest launcher: runs a test, and if it is still running after HS_TEST_STACK_DUMP_SEC seconds (default 1500, below the
# ctest timeout) prints the stack of every thread of the test and of the processes it spawned, so the output of a hung
# test shows where it is stuck. If the test or a process it spawned crashes and leaves a core.<pid> file (CI sets
# kernel.core_pattern=core.%p), prints the stacks from that core.

ulimit -c unlimited 2> /dev/null
start_marker=$(mktemp)
"$@" &
test_pid=$!
limit=${HS_TEST_STACK_DUMP_SEC:-1500}

descendants() {
    local p
    for p in $(ps -o pid= --ppid "$1" 2>/dev/null); do
        echo "$p"
        descendants "$p"
    done
}

dump_stacks() {
    local gdb=(gdb)
    # attaching to a process that isn't our child needs ptrace rights (yama ptrace_scope), which sudo provides on CI
    if [[ $EUID -ne 0 ]] && sudo -n true 2>/dev/null; then gdb=(sudo -n gdb); fi
    local p
    for p in $test_pid $(descendants $test_pid); do
        echo "==================== stacks of pid $p: $(tr '\0' ' ' < /proc/$p/cmdline 2>/dev/null)"
        "${gdb[@]}" -p "$p" -batch -ex "set pagination off" -ex "thread apply all bt" 2>&1 | grep -v "^\[New LWP"
    done
}

(
    waited=0
    while (( waited < limit )); do
        sleep 5 > /dev/null 2>&1
        kill -0 $test_pid 2> /dev/null || exit 0
        waited=$((waited + 5))
    done
    echo "==================== test still running after ${limit}s, dumping stacks"
    if command -v gdb > /dev/null; then dump_stacks; else echo "gdb not found, cannot dump stacks"; fi
) &
watcher_pid=$!

wait $test_pid
rc=$?
kill $watcher_pid 2> /dev/null

if command -v gdb > /dev/null; then
    for core in $(find . -maxdepth 1 -name 'core.*' -newer "$start_marker" 2> /dev/null); do
        exe=$(gdb -batch -c "$core" 2>&1 | sed -n "s/^Core was generated by \`\([^ ']*\).*/\1/p")
        [[ -x "$exe" ]] || exe=$1
        echo "==================== stacks from $core ($exe)"
        gdb -batch -ex "set pagination off" -ex "thread apply all bt" "$exe" "$core" 2>&1 | grep -v "^\[New LWP"
        rm -f "$core"
    done
fi
rm -f "$start_marker"
exit $rc
